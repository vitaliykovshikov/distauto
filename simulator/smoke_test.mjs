import assert from 'node:assert/strict';
import create from '../dist/column.mjs';
const module=await create();
const wrap=(name,result,args=[])=>module.cwrap('sim_'+name,result,args);
const init=wrap('init',null),step=wrap('step',null,['number']);
const temp=wrap('temperature',null,['number']),sensor=wrap('sensor',null,['number']);
const clear=wrap('clear_args',null),arg=wrap('arg',null,['string','string']);
const request=wrap('request','number',['string','number']),response=wrap('response','string');
const state=()=>JSON.parse(wrap('state','string')());
function call(path,values={},method='POST'){
 clear();for(const [key,value] of Object.entries(values))arg(key,String(value));
 const code=request(path,method==='POST'?1:2),text=response();
 return {code,text,json:()=>JSON.parse(text)};
}
init();step(1000);
assert.equal(call('/status',{},'GET').json().mode,'IDLE');
assert.equal(state().deliveredMl,0);
assert.equal(call('/auto/start').code,409);
assert.equal(call('/plan',{},'GET').code,405);
const p=call('/plan',{vol:10,abv:40,h:1,d:4,headsPct:10,tailsPct:15,strengthPct:96,decrementPct:10,reduceDt:.2});
assert.equal(p.code,200);const plan=p.json();
assert.equal(plan.aa,4000);assert.equal(plan.bodyMl,3125);
assert.equal(call('/auto/start',{revision:plan.revision,headsRate:400,bodyRate:4000}).code,200);
step(31*60000);assert.equal(state().phase,'HEADS');
step(65*60000);assert.equal(state().phase,'STAB');assert.equal(state().valve,false);
assert.ok(state().headsMl>=plan.headsMl && state().headsMl<plan.headsMl+2);
call('/auto/swap');step(10*60000);assert.equal(state().phase,'BODY');
temp(78.3);step(64000);assert.ok(Math.abs(state().factor-.9)<.0001);
step(60000);assert.ok(Math.abs(state().factor-.81)<.0001);
call('/stop',{on:1},'GET');step(30000);assert.equal(state().valve,false);
call('/stop',{on:0},'GET');step(1000);
call('/auto/end');step(2000);assert.equal(state().phase,'ABORT');assert.equal(state().valve,false);
call('/auto/end');step(2000);assert.equal(call('/status',{},'GET').json().mode,'IDLE');assert.equal(state().valve,false);
assert.equal(call('/calib/save',{sec:10,ml:25},'GET').code,200);
assert.equal(call('/status',{},'GET').json().flow,2.5);
sensor(0);step(7000);
assert.equal(call('/auto/start',{revision:plan.revision,headsRate:400,bodyRate:4000}).code,400);
console.log('WebAssembly: full warmup → heads → swap → body, repeated decrement, pause, stop, calibration, sensor failure: OK');

// A fresh instance exercises the same sketch's new modes without carrying the previous run.
const fresh=await create();
const fn=(name,result,args=[])=>fresh.cwrap('sim_'+name,result,args);
const fstep=fn('step',null,['number']),fclear=fn('clear_args',null),farg=fn('arg',null,['string','string']);
const freq=fn('request','number',['string','number']),fresponse=fn('response','string');
function featureCall(path,values={},method='POST'){
 fclear();for(const [key,value] of Object.entries(values))farg(key,String(value));
 const code=freq(path,method==='POST'?1:2),text=fresponse();return {code,text,json:()=>JSON.parse(text)};
}
fn('init',null)();fstep(1000);
assert.equal(featureCall('/features',{},'GET').json().simulator,true);
const rp=featureCall('/recipe/plan',{vol:10,abv:40,h:1,d:4,strengthPct:96,pct:3,spit:4000,drip:400,stream:800});
assert.equal(rp.code,200);assert.equal(rp.json().totalPct,8);assert.equal(rp.json().targetsMl[2],125);
assert.equal(featureCall('/features',{},'GET').json().maxRate,4000);
assert.equal(featureCall('/recipe/start',{revision:rp.json().revision,date:'2026-11-19T18:00:00.000Z',label:'Тест 2–3–15'}).code,200);
fstep(30*60000);assert.equal(featureCall('/status',{},'GET').json().phase,'SPIT');
featureCall('/recipe/rate',{stage:0,rate:0});fstep(3000);assert.equal(featureCall('/status',{},'GET').json().valve,false);
featureCall('/recipe/rate',{stage:0,rate:4000});fstep(100000);assert.equal(featureCall('/status',{},'GET').json().phase,'DRIP');
featureCall('/recipe/rate',{stage:1,rate:800});fstep(10*60000);assert.equal(featureCall('/status',{},'GET').json().phase,'STREAM');
fstep(10*60000);let pending=featureCall('/status',{},'GET').json();assert.equal(pending.stageAwaiting,true);assert.equal(pending.valve,false);
assert.equal(featureCall('/manual/start',{profile:1}).code,409);
function decide(choice){const d=featureCall('/status',{},'GET').json();return featureCall('/stage/choice',{choice,decision:d.stageDecision});}
assert.equal(decide('continue').code,200);fstep(1000);assert.equal(featureCall('/status',{},'GET').json().extraHeads,true);
featureCall('/stage/end');assert.equal(decide('next').code,200);fstep(20000);
let body=featureCall('/report',{},'GET').json();assert.equal(body.meta.kind,'recipe');assert.ok(body.summary.volumesMl[4]>0);
featureCall('/stage/end');assert.equal(decide('continue').code,200);fstep(10000);
featureCall('/stage/end');assert.equal(decide('next').code,200);fstep(10000);
assert.equal(featureCall('/status',{},'GET').json().phase,'TAILS');
featureCall('/stage/end');assert.equal(decide('next').code,200);
const report=featureCall('/report',{},'GET').json();
assert.equal(report.meta.id,body.meta.id);assert.equal(report.meta.startedAt,'2026-11-19T18:00:00.000Z');
assert.equal(report.summary.active,false);assert.equal(report.summary.result,'completed');assert.ok(report.summary.volumesMl[5]>0);
assert.ok(report.samples.length>0&&report.samples.length<=600);assert.ok(featureCall('/report.csv',{},'GET').text.includes('#summary,'));
assert.deepEqual(featureCall('/history',{},'GET').json(),[]);
featureCall('/manual/config',{profile:0,set:78.3,hyst:.3,rate:500});featureCall('/manual/config',{profile:1,set:78.3,hyst:.3,rate:2000});
featureCall('/manual/start',{profile:0,date:'2026-11-19T19:00:00.000Z'});fstep(20000);
const mid=featureCall('/report',{},'GET').json();featureCall('/stage/end');decide('next');fstep(20000);
const switched=featureCall('/report',{},'GET').json();assert.equal(mid.meta.id,switched.meta.id);assert.ok(switched.summary.volumesMl[3]>0);
featureCall('/manual',{on:0},'GET');assert.equal(featureCall('/report',{},'GET').json().summary.active,false);
featureCall('/preset/save',{name:'Мій режим',kind:'recipe',config:'vol=10&abv=40&recipePct=3'});
assert.equal(featureCall('/presets',{},'GET').json()[0].name,'Мій режим');
console.log('WebAssembly: 4000 range, staged confirmation, recipe heads → manual body/tails, one dated report, CSV and named presets: OK');
